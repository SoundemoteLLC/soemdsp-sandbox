import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const context = vm.createContext({ nodeSliderMetadata: s => ({ min: 0, max: 1000, mid: 100, def: 100, ...s.metadata }) });
vm.runInContext(fs.readFileSync(new URL("../public/node-graph-slider-dragging.js", import.meta.url), "utf8"), context);
const expand = (value, metadata = {}, dataset = {}) => context.nodeSliderMetadataForTypedMaximum({ metadata, dataset }, value);
assert.equal(expand(5000).max, 5000);
assert.equal(expand(5000).mid, 100); assert.equal(expand(5000).def, 100);
for (const v of [NaN, Infinity, 999, 1000, -1]) assert.equal(expand(v), null);
for (const m of [{ choices: ["Off", "On"] }, { kind: "seed" }, { wraparound: true }]) assert.equal(expand(5000, m), null);
for (const c of ["cpu", "gpu", "ram", "memory"]) assert.equal(expand(5000, {}, { constraint: c }), null);
assert.equal(expand(5000, {}, { hardClamp: "true" }), null);
assert.equal(expand(5000, {}, { hardClamp: "true", hardMax: "2000" }).max, 2000);
assert.equal(expand(1500, {}, { constraint: "cpu", hardMax: "2000" }).max, 1500);
const node = { id: "child", type: "test", paramMeta: { release: { max: 1000, mid: 100, alias: "kept", domainOffset: 42 } } };
context.nodeGraphMvp = { patch: { nodes: [node] } };
context.normalizeNodeGraphPatchParameterMetadata = (_type, _key, m) => ({ ...m });
context.setNodeSliderMetadata = (_s, m) => {
  assert.equal(node.paramMeta.release.max, 5000, "save metadata before repaint");
  assert.equal(m.alias, "kept"); assert.equal(m.domainOffset, 42);
};
context.nodeGraphApplyTypedSliderMaximum({ dataset: { param: "release" } }, node, { max: 5000 });
assert.equal(node.paramMeta.release.max, 5000);
const owner = { id: "meta", type: "meta", paramMeta: { mx_release: { max: 1000, alias: "shell" } } };
node.ownerMetamoduleId = owner.id;
context.nodeGraphMvp.patch.nodes.push(owner);
context.nodeGraphIsContainerShellType = type => type === "meta";
context.nodeGraphMetamoduleResolveExposeTarget = () => ({ child: node, paramKey: "release" });
context.nodeGraphMetamoduleIsParamExposed = () => true;
context.nodeGraphMetamoduleExposeParamKey = () => "mx_release";
context.nodeGraphSliderForParameter = () => null;
context.setNodeSliderMetadata = () => {};
context.nodeGraphApplyTypedSliderMaximum({ dataset: { param: "mx_release" } }, owner, { max: 6000 });
assert.equal(node.paramMeta.release.max, 6000); assert.equal(owner.paramMeta.mx_release.max, 6000);
assert.equal(node.paramMeta.release.alias, "kept"); assert.equal(owner.paramMeta.mx_release.alias, "shell");
context.nodeGraphApplyTypedSliderMaximum({ dataset: { param: "release" } }, node, { max: 7000 });
assert.equal(node.paramMeta.release.max, 7000); assert.equal(owner.paramMeta.mx_release.max, 7000);
console.log("Typed maximum: expansion, unchanged midpoint/default, invalid/in-range entries, choices, wrapping, resources and metadata preservation pass.");
